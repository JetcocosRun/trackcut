//! Локализация человекочитаемого вывода CLI.
//!
//! Ключ таблицы — русский текст. `tr` принимает `&'static str` (литералы CLI),
//! `tr_str` — произвольную строку (например, подписи из core), `fill` подставляет
//! аргументы в `{}` уже после перевода.

macro_rules! lang_table {
    ($($ru:literal => $tr:literal),* $(,)?) => {
        pub fn lookup(text: &str) -> Option<&'static str> {
            match text {
                $($ru => Some($tr),)*
                _ => None,
            }
        }
    };
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Ru,
    En,
    De,
    Fr,
    Es,
    It,
    Ja,
    Zh,
    Kk,
}

impl Lang {
    pub fn from_code(code: &str) -> Option<Self> {
        Some(match code.to_ascii_lowercase().as_str() {
            "ru" => Lang::Ru,
            "en" => Lang::En,
            "de" => Lang::De,
            "fr" => Lang::Fr,
            "es" => Lang::Es,
            "it" => Lang::It,
            "ja" => Lang::Ja,
            "zh" => Lang::Zh,
            "kk" => Lang::Kk,
            _ => return None,
        })
    }
}

/// Перевод литерала. Для русского возвращается исходный текст.
pub fn tr(lang: Lang, text: &'static str) -> &'static str {
    match lang {
        Lang::Ru => text,
        Lang::En => en::lookup(text).unwrap_or(text),
        Lang::De => de::lookup(text).unwrap_or(text),
        Lang::Fr => fr::lookup(text).unwrap_or(text),
        Lang::Es => es::lookup(text).unwrap_or(text),
        Lang::It => it::lookup(text).unwrap_or(text),
        Lang::Ja => ja::lookup(text).unwrap_or(text),
        Lang::Zh => zh::lookup(text).unwrap_or(text),
        Lang::Kk => kk::lookup(text).unwrap_or(text),
    }
}

/// Перевод строки, полученной не из литерала CLI (например, из core).
/// Если перевода нет, строка остаётся как есть.
pub fn tr_str(lang: Lang, text: &str) -> &str {
    if lang == Lang::Ru {
        return text;
    }
    match lang {
        Lang::Ru => text,
        Lang::En => en::lookup(text).unwrap_or(text),
        Lang::De => de::lookup(text).unwrap_or(text),
        Lang::Fr => fr::lookup(text).unwrap_or(text),
        Lang::Es => es::lookup(text).unwrap_or(text),
        Lang::It => it::lookup(text).unwrap_or(text),
        Lang::Ja => ja::lookup(text).unwrap_or(text),
        Lang::Zh => zh::lookup(text).unwrap_or(text),
        Lang::Kk => kk::lookup(text).unwrap_or(text),
    }
}

/// Подставляет аргументы в `{}` переведённого шаблона по порядку.
pub fn fill(lang: Lang, template: &'static str, args: &[String]) -> String {
    let mut out = tr(lang, template).to_string();
    for arg in args {
        if let Some(pos) = out.find("{}") {
            out.replace_range(pos..pos + 2, arg);
        }
    }
    out
}

/// Единица размера из core (`format_size`) на нужном языке.
pub fn size_unit(lang: Lang, unit: &str) -> Option<&'static str> {
    Some(match lang {
        Lang::Ru | Lang::Kk => match unit {
            "Б" => "Б",
            "КБ" => "КБ",
            "МБ" => "МБ",
            "ГБ" => "ГБ",
            "ТБ" => "ТБ",
            _ => return None,
        },
        _ => match unit {
            "Б" => "B",
            "КБ" => "KB",
            "МБ" => "MB",
            "ГБ" => "GB",
            "ТБ" => "TB",
            _ => return None,
        },
    })
}

